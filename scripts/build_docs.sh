#!/usr/bin/env sh
# Build the module reference (priv/docs/reference.md) from ExDoc's per-module
# markdown, then it is served as a normal in-app page (/reference) — so it
# inherits the app's base handling, auth, navbar and theming. No static
# sub-site, no <base> rewriting, works under any access path.
set -Eeuo pipefail
cd "$(dirname "$0")/.."

MIX_ENV=dev mix deps.get
MIX_ENV=dev mix docs

mkdir -p priv/docs
{
  echo "# Module Reference"
  echo
  echo "_Every public module, type and function. Generated by ExDoc — the same source a hex.pm package publishes._"
  echo
  for f in doc/HomeElixir*.md; do
    [ -e "$f" ] || continue
    cat "$f"
    printf "\n\n---\n\n"
  done
} > priv/docs/reference.md

# Drop ExDoc's per-module "Consult api-reference.md" footers (dangling here —
# this is a single page, not the multi-page site).
sed -i '/api-reference\.md/d' priv/docs/reference.md

echo "reference built -> priv/docs/reference.md ($(wc -l < priv/docs/reference.md) lines)"
